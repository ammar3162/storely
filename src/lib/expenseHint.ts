// أصناف شكلها مصروف مو مخزون (تنظيف، غاز، صيانة، رسوم...) — تنبيه بس، ما يغيّر شي تلقائياً.
// المخزون = أصناف تُصرف وتُجرد. المشتريات (مصروف) = أشياء ما تُخزّن.
const WORDS = [
  'منظف', 'منظفات', 'تنظيف', 'صابون', 'كلور', 'فلاش', 'معطر', 'مطهر', 'ديتول', 'مبيد', 'أكياس قمامة', 'اكياس قمامة', 'كيس زبالة', 'أكياس زبالة',
  'غاز', 'اسطوانة غاز', 'أسطوانة غاز', 'تعبئة غاز', 'كهرباء', 'فاتورة مياه', 'فاتورة كهرباء', 'إنترنت', 'انترنت', 'جوال', 'شريحة',
  'صيانة', 'إصلاح', 'اصلاح', 'تصليح', 'سباك', 'سباكة', 'كهربائي', 'فني', 'قطع غيار',
  'أجرة', 'اجرة', 'توصيل', 'نقل', 'شحن', 'رسوم', 'اشتراك', 'إيجار', 'ايجار', 'خدمة', 'عمالة',
  'قرطاسية', 'أقلام', 'اقلام', 'ورق طباعة', 'حبر', 'طابعة', 'أدوات مكتبية',
]
const norm = (s: string) => String(s || '').toLowerCase().replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/\s+/g, ' ').trim()
const KEYS = WORDS.map(norm)

/** الاسم يوحي بمصروف (مو صنف مخزون)؟ */
export function looksLikeExpense(name: string | null | undefined): boolean {
  const n = norm(name || '')
  if (!n) return false
  return KEYS.some(k => n === k || n.startsWith(k + ' ') || n.endsWith(' ' + k) || n.includes(' ' + k + ' ') || (k.length >= 4 && n.includes(k)))
}
