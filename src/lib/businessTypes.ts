export const catsFor = (type?: string | null) => CATS_BY_TYPE[type || ''] || CATS_BY_TYPE['أخرى']

// الوحدات حسب النشاط — ولو الصنف عنده وحدة قديمة مو بالقائمة نخليها عشان ما تضيع
export function unitsFor(type?: string | null, current?: string | null): string[] {
  const list = UNITS_BY_TYPE[type || ''] || DEFAULT_UNITS
  return current && !list.includes(current) ? [current, ...list] : list
}

// نفس الشي للفئة: فئة قديمة أو مكتوبة يدوي تبقى ظاهرة
export function catsWith(type?: string | null, current?: string | null): string[] {
  const list = catsFor(type)
  return current && !list.includes(current) ? [current, ...list] : list
}
