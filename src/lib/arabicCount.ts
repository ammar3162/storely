/** صيغة الوحدة المناسبة للعدد */
export function unitFor(n: number | string | null | undefined, unit: string | null | undefined): string {
  const u = (unit || '').trim()
  if (!u) return ''
  const v = Math.abs(Number(n))
  if (!Number.isFinite(v) || !Number.isInteger(v)) return u
  const tail = v % 100
  return tail >= 3 && tail <= 10 && PLURAL[u] ? PLURAL[u] : u
}

/** «6 قطع» — العدد كما هو مع الوحدة المناسبة (بدون وحدة يرجع العدد بس) */
export function qtyUnit(n: number | string | null | undefined, unit: string | null | undefined): string {
  const u = unitFor(n, unit)
  const num = n == null || n === '' ? '' : String(n)
  return u ? `${num} ${u}`.trim() : num
}

