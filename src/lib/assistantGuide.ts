export async function assistantGuide(db: SupabaseClient): Promise<string> {
  const { data } = await db.from('help_videos').select('page_key,youtube_id')
  const video = new Map(((data || []) as any[]).map(v => [v.page_key, v.youtube_id]))
  const lines = HELP_PAGES.filter(p => STEPS[p.key] || video.has(p.key)).map(p => {
    const v = video.get(p.key)
    return `• ${p.label}: ${STEPS[p.key] || ''}${v ? ` | فيديو الشرح: https://youtu.be/${v}` : ''}`
  })
  return `═══ دليل استخدام النظام ═══
لو سأل «كيف أسوي كذا؟»: اشرح الخطوات باختصار من الدليل، واذكر اسم الصفحة من القائمة، وحط رابط فيديو الشرح لو موجود. لو الدليل ما يغطي السؤال، أو المشكلة تبدو خللاً في النظام: قل له يضغط «ما انحلت مشكلتك؟ أرسلها للدعم الفني» تحت الرد، وتوصل المحادثة كاملة لفريق الدعم ويصله الرد في الإشعارات. لا تذكر واتساب للدعم.
${lines.join('\n')}`
}
